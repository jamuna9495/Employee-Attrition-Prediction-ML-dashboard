print(df.columns.tolist())


# ============================================================
# 2. SELECT FEATURES
# ============================================================

# Dependent variable
target = "Attrition"

# 5 Independent variables
features = [
    "Age",
    "Business Travel",
    "Over Time",
    "Job Satisfaction",
    "Years At Company"
]

X = df[features].copy()
y = df[target].copy()


# ============================================================
# 3. HANDLE MISSING VALUES
# ============================================================

print("\nMissing values:")
print(X.isnull().sum())

# Fill numerical missing values
X["Age"] = X["Age"].fillna(X["Age"].median())
X["Job Satisfaction"] = X["Job Satisfaction"].fillna(
    X["Job Satisfaction"].median()
)
X["Years At Company"] = X["Years At Company"].fillna(
    X["Years At Company"].median()
)

# Fill categorical missing values
X["Business Travel"] = X["Business Travel"].fillna(
    X["Business Travel"].mode()[0]
)

X["Over Time"] = X["Over Time"].fillna(
    X["Over Time"].mode()[0]
)


# ============================================================
# 4. ENCODE CATEGORICAL VARIABLES
# ============================================================

# Business Travel:
# Travel_Rarely
# Travel_Frequently
# Non-Travel

X = pd.get_dummies(
    X,
    columns=["Business Travel", "Over Time"],
    drop_first=True
)


# ============================================================
# 5. ENCODE TARGET VARIABLE
# ============================================================

# Yes = 1
# No = 0

y = y.map({
    "Yes": 1,
    "No": 0
})

# Check target
print("\nTarget values:")
print(y.value_counts())


# ============================================================
# 6. TRAIN TEST SPLIT
# ============================================================

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("\nTraining data:", X_train.shape)
print("Testing data:", X_test.shape)


